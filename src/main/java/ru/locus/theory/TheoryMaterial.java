package ru.locus.theory;

import ru.locus.file.FileKey;
import ru.locus.taxonomy.TaxonomyNodeId;

/**
 * Теоретический материал — вторая после Задач начинка рубрикатора (ADR-0018):
 * название, узел и содержимое.
 *
 * Содержимое — <b>ровно одно</b> из двух: приложенный файл либо ссылка
 * на внешний адрес. Материал без того и другого показывался бы в списке
 * настоящим, а открыть его было бы нечем; материал с обоими сразу оставлял бы
 * непонятным, что открывается по нажатию и что теряется при правке.
 *
 * Правила стоят в компактном конструкторе, а не в сервисе, — по образцу
 * {@link ru.locus.problem.Problem}: запись, собранная в обход правил,
 * не должна существовать ни в памяти, ни тем более в базе. То же правило
 * «ровно одно» стоит и проверочным ограничением в схеме
 * ({@code 0005-theory-materials.yaml}): инвариант, выразимый схемой,
 * выражается схемой, иначе он держится на том, что никто не пишет в таблицу
 * мимо кода.
 *
 * Узел — <b>любой</b>, и Раздел, и Тема (ADR-0032). Правило «смысл только
 * в листьях», действующее для Задач и отметок Владения, на теорию
 * не распространяется: оно введено ради корректности измерения владения,
 * а у материала измерения нет.
 *
 * Владельца у материала нет: теория принадлежит общей библиотеке (ADR-0027).
 *
 * @param node  узел, на котором лежит материал; на всём его поддереве материал
 *              виден, но хранится это не здесь — наследование вычисляется
 *              подъёмом по предкам
 * @param file  ключ приложенного файла; {@code null}, если материал — ссылка
 * @param link  внешний адрес; {@code null}, если материал — файл
 */
public record TheoryMaterial(TheoryMaterialId id,
                             String title,
                             TaxonomyNodeId node,
                             FileKey file,
                             String link) {

    public TheoryMaterial {
        if (id == null) {
            throw new IllegalArgumentException("У Теоретического материала должен быть идентификатор");
        }
        title = requiredTitle(title);
        if (node == null) {
            throw new IllegalArgumentException("Теоретический материал должен лежать на узле рубрикатора");
        }
        link = normalizedLink(link);
        requireContent(file, link);
    }

    /**
     * Проверка содержимого, вынесенная из конструктора отдельно, — ею
     * пользуется и сервис теории до того, как материал заведён и записи
     * ещё нет.
     *
     * Одна проверка на оба случая, а не две одинаковые: разойдясь, они дали бы
     * материал, который сохраняется, но не читается обратно.
     */
    static void requireContent(FileKey file, String link) {
        if (file == null && link == null) {
            throw new IllegalArgumentException(
                    "Теоретическому материалу нужен файл либо ссылка");
        }
        if (file != null && link != null) {
            throw new IllegalArgumentException(
                    "У Теоретического материала содержимое бывает только одно: файл либо ссылка");
        }
    }

    /**
     * Название обязательно и не пустое после отсечения пробелов по краям:
     * текста материала система не хранит и не разбирает, и в списке материал
     * различается только названием — безымянный в нём неотличим от любого
     * другого.
     */
    static String requiredTitle(String title) {
        if (title == null || title.isBlank()) {
            throw new IllegalArgumentException("У Теоретического материала должно быть название");
        }
        return title.trim();
    }

    /**
     * Ссылка приводится к виду, в котором её можно отдать браузеру: пустая
     * и состоящая из пробелов — это отсутствие ссылки, а не ссылка.
     *
     * Схема проверяется, доступность адреса — нет. {@code javascript:}
     * в атрибуте {@code href} — исполняемый код в чужом браузере, и попадёт
     * он туда через общую библиотеку, то есть ко всем Учителям сразу.
     * А отвечает ли адрес, система не спрашивает: это сетевое обращение
     * из обработчика запроса, и протухшую ссылку всё равно обнаружит человек,
     * который по ней пойдёт (ADR-0017).
     */
    static String normalizedLink(String link) {
        if (link == null) {
            return null;
        }
        String trimmed = link.trim();
        if (trimmed.isEmpty()) {
            return null;
        }
        if (!trimmed.startsWith("http://") && !trimmed.startsWith("https://")) {
            throw new IllegalArgumentException("Ссылка должна начинаться с http:// или https://: " + trimmed);
        }
        return trimmed;
    }

    /** Материал — приложенный файл, а не внешний адрес. */
    public boolean hasFile() {
        return file != null;
    }
}
