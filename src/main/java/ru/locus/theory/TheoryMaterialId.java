package ru.locus.theory;

/**
 * Идентификатор Теоретического материала — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.problem.ProblemId} и
 * {@link ru.locus.taxonomy.TaxonomyNodeId}: материал живёт рядом с узлом
 * дерева и ссылается на него, и два числа, стоящие рядом в одном вызове,
 * рано или поздно меняются местами. Разные типы делают такую перестановку
 * ошибкой компиляции, а не материалом, уехавшим на чужой узел.
 *
 * Номером человеку этот идентификатор не показывается — в списке материал
 * различается названием (в отличие от Задачи, у которой номер и есть id,
 * ADR-0029).
 *
 * Материал — общая библиотека, под Администратором; владельца у него нет
 * и быть не должно (ADR-0027).
 */
public record TheoryMaterialId(long value) {

    public TheoryMaterialId {
        if (value <= 0) {
            throw new IllegalArgumentException(
                    "Идентификатор Теоретического материала должен быть положительным: " + value);
        }
    }
}
