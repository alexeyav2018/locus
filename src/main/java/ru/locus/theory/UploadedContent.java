package ru.locus.theory;

/**
 * Присланное содержимое материала до укладки в хранилище: байты приложенного
 * файла с типом, как его назвал браузер, либо внешний адрес.
 *
 * Одна запись на оба случая, а не два параметра и не два метода сервиса:
 * содержимое материала — <b>ровно одно из двух</b>, и форма присылает оба поля
 * всегда, потому что заполненность одного из них — как раз то, что человек
 * выбирает. Разбирать, что именно прислано, приходится в одном месте; двумя
 * методами это разбирательство переехало бы в контроллер, где ему не место.
 *
 * Своя запись, а не общая с Задачей: теория от области Задач не зависит
 * и зависеть не должна (design.md, «Goals»), а состав здесь другой — файл
 * необязателен, зато есть ссылка.
 *
 * Пережатия здесь нет: решает вызывающий, по типу содержимого
 * (standards.md, «Файлы»). Для теории решает {@link TheoryService} — и в
 * отличие от Задачи, где пережимать нечего, изображение он пережимает.
 *
 * @param file        байты приложенного файла; {@code null} или пустой массив
 *                    означают, что файла не приложили
 * @param contentType тип содержимого, как его назвал браузер
 * @param link        внешний адрес; пустой и состоящий из пробелов означает,
 *                    что адреса не указали
 */
public record UploadedContent(byte[] file, String contentType, String link) {

    /** Материал с приложенным файлом. */
    public static UploadedContent ofFile(byte[] file, String contentType) {
        return new UploadedContent(file, contentType, null);
    }

    /** Материал со ссылкой на внешний адрес. */
    public static UploadedContent ofLink(String link) {
        return new UploadedContent(null, null, link);
    }

    public boolean hasFile() {
        return file != null && file.length > 0;
    }
}
