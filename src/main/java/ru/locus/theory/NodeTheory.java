package ru.locus.theory;

/**
 * Материал в списке выбранного узла: сам материал, имя узла, с которого он
 * пришёл, и признак «свой».
 *
 * Отдельная запись, а не голый {@link TheoryMaterial}, потому что список
 * смешивает материалы разных узлов: свои и унаследованные от предков. Шаблону
 * остаётся показать или не показать источник — считать ему нечего, и второго
 * места, где решается «свой ли материал», не появляется.
 *
 * Имя узла, а не его идентификатор: список читает человек, и «Тригонометрия»
 * говорит ему то, чего не скажет число. Полный путь от корня здесь не нужен —
 * узлы списка лежат на одной ветви с выбранным, и различаются они именами.
 *
 * @param source узел, на котором лежит материал; для своего материала — сам
 *               выбранный узел
 * @param own    материал лежит на выбранном узле, а не унаследован; правится
 *               материал там, где лежит, и это единственное, ради чего признак
 *               нужен экрану
 */
public record NodeTheory(TheoryMaterial material, String source, boolean own) {

    public NodeTheory {
        if (material == null) {
            throw new IllegalArgumentException("В списке узла не бывает пустого материала");
        }
        if (source == null || source.isBlank()) {
            throw new IllegalArgumentException("У материала в списке должен быть назван узел-источник");
        }
    }
}
