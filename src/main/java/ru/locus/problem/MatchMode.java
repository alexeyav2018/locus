package ru.locus.problem;

/**
 * Способ соединить несколько значений внутри одного условия поиска
 * (glossary.md, «Перечисления»; ADR-0031).
 *
 * Условие по Методу и условие по Характеристике берут любое число значений,
 * и смысл у нескольких значений двоякий. «Все сразу» сужает — так ищут
 * задачу, на которой сходятся формулы приведения и двойной угол. «Любое из»
 * расширяет — так собирают задание на три приёма, разобранных за неделю.
 * Оба прочтения нужны в работе, поэтому выбирает между ними учитель, а не
 * система: выбранное за него прочтение отбирало бы не то, что он имел
 * в виду, и молча.
 *
 * Значения не придумываются по месту, а берутся из словаря: имя,
 * придуманное здесь, разошлось бы со словарём молча.
 *
 * Разные условия между собой соединяются по «и» всегда, и этого выбора
 * здесь нет: условия отвечают за разные измерения разметки, и «Метод либо
 * Часть» — не вопрос, который кто-то задаёт.
 */
public enum MatchMode {

    /** Задача размечена каждым выбранным значением. */
    ALL("все сразу"),

    /** Задача размечена хотя бы одним выбранным значением. */
    ANY("любое из");

    private final String title;

    MatchMode(String title) {
        this.title = title;
    }

    /**
     * Имя способа по-русски — для показа человеку. Перевод живёт здесь,
     * а не в шаблоне, по той же причине, что и у {@link ExamPart}: шаблонов,
     * показывающих способ, будет больше одного, и разъехались бы они молча
     * (ADR-0028: имена констант английские, интерфейс русский).
     */
    public String title() {
        return title;
    }
}
