package ru.locus.problem;

/**
 * Присланный файл до укладки в хранилище: содержимое и тип, как их назвал
 * браузер.
 *
 * Отдельная запись, а не пара параметров: содержимое и тип нужны только
 * вместе, и разъехаться местами у двух файлов Задачи они не должны — условие,
 * положенное под ключ решения, ничем себя не выдаст.
 *
 * Пережатия здесь нет и быть не должно: Задача — это PDF, а пережимается
 * только изображение (standards.md, «Файлы»). Решает вызывающий, по типу
 * содержимого, и вызывающий здесь решает не пережимать.
 */
public record UploadedFile(byte[] content, String contentType) {

    public boolean isEmpty() {
        return content == null || content.length == 0;
    }
}
