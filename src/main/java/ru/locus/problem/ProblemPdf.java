package ru.locus.problem;

/**
 * PDF слота Задачи, как его прислали: готовый файл либо порядок сборки
 * из черновиков (ADR-0041).
 *
 * Запечатан намеренно: вариантов ровно два, и {@link ProblemService}
 * разбирает их перебором — третий вариант, заведённый молча, не скомпилирует
 * этот перебор, а не проскочит мимо него. Что слот получил ровно один
 * вариант, а не оба, решает разбор формы: сервис получает тип, а не выбор.
 */
public sealed interface ProblemPdf permits UploadedFile, PdfAssemblyOrder {

    /** Ничего не прислано: пустой файл или порядок без строк. */
    boolean isEmpty();
}
