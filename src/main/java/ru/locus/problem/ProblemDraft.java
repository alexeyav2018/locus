package ru.locus.problem;

import java.time.Instant;
import ru.locus.user.UserId;

/**
 * Черновик Задачи — распознанная, но не утверждённая Задача (ADR-0059).
 *
 * Личный у загрузившего: строки сборки ссылаются на его Черновики сборки,
 * и чужой черновик неотличим от несуществующего. Правят его двое —
 * Помощник инструментами и учитель на странице вычитки, — поэтому у него
 * есть версия, растущая с каждой записью, и отметка, кто правил последним
 * (ADR-0056). Утверждённый черновик становится Задачей и удаляется.
 *
 * @param version   растёт с каждой записью; правка по старой отклоняется
 * @param changedBy кто записал последним
 * @param changedAt когда записан последним — от этого момента считается
 *                  срок уборки
 */
public record ProblemDraft(ProblemDraftId id,
                           UserId owner,
                           ProblemDraftContent content,
                           long version,
                           Editor changedBy,
                           Instant changedAt,
                           Instant createdAt) {

    /**
     * Кто записал черновик. Передаёт вызывающий константой — контроллер
     * страницы вычитки или инструмент Помощника, — а не узнаёт сервис
     * по виду входа: личность у обоих одна (design.md, Р3).
     */
    public enum Editor {
        /** Вошедший на странице вычитки. */
        OWNER,
        /** Помощник инструментом под личностью учителя. */
        ASSISTANT
    }
}
