package ru.locus.problem;

/**
 * Часть ЕГЭ, к которой относится Задача (glossary.md, «Перечисления»).
 *
 * Значения не придумываются по месту, а берутся из словаря: имя, придуманное
 * здесь, разошлось бы со словарём молча, а хранится оно строкой в колонке
 * {@code problem.exam_part} — то есть переживёт и переименование.
 *
 * Разница между частями предметная, а не техническая: в первой ответ — целое
 * число или конечная десятичная дробь, во второй — произвольное выражение.
 * Система пользуется этим только для поиска и подбора и никаких проверок
 * ответа на этом не строит (ADR-0014).
 */
public enum ExamPart {

    /** Первая часть ЕГЭ. */
    FIRST("первая часть"),

    /** Вторая часть ЕГЭ. */
    SECOND("вторая часть");

    private final String title;

    ExamPart(String title) {
        this.title = title;
    }

    /**
     * Имя Части по-русски — для показа человеку. Русский остаётся ведущим
     * языком интерфейса, а имена констант английские (ADR-0028), поэтому
     * перевод живёт здесь, а не в шаблоне: шаблонов, показывающих Часть,
     * будет несколько, и разъехались бы они молча.
     */
    public String title() {
        return title;
    }
}
