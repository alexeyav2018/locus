package ru.locus.problem;

import java.util.Optional;

/**
 * Вопрос, который библиотека задаёт личным контурам учителей: использована ли
 * эта Задача?
 *
 * <p>Использованной считается Задача, вошедшая хотя бы в одно Задание,
 * имеющая хотя бы одну Работу или вошедшая хотя бы в одну Разминку.
 * Отвечают {@code AssignmentsOfProblem} и {@code WarmupsOfProblem} — оба
 * считают по всем Учителям (ADR-0036). Своего ответчика у Работы нет,
 * и это не пропуск: Работа принимается только по Задаче своего Задания,
 * а Задание с Работой не удаляется (ADR-0037), так что Задача с Работой
 * всегда названа ответом Заданий.
 *
 * <p><b>Каждая сущность, ссылающаяся на Задачу, обязана ответить на этот
 * вопрос</b>:
 *
 * <ul>
 *   <li>Задание — Задача вошла в чью-то выдачу; работа {@code assignments},
 *       ответила;</li>
 *   <li>Работа — по Задаче принято решение ученика; работа
 *       {@code submission-review}, покрыта ответом Заданий;</li>
 *   <li>Разминка — Задачу решали на занятии, и по ней ставились отметки;
 *       работа {@code warmup}, ответила (ADR-0061).</li>
 * </ul>
 *
 * <p>Забытая реализация — тихая порча чужих данных: правит Задачу
 * Администратор, а он не видит ни чужих Заданий, ни чужих Работ, ни чужих
 * Разминок, ни чужих отметок. Правка разметки выданной Задачи меняет основание ячеек владения
 * задним числом, удаление — стирает у чужого учителя смысл его Работы,
 * и уведомлений в системе нет (ADR-0030, ADR-0017).
 *
 * <p>Вопрос задаётся из личного контура о библиотечной сущности — направление
 * зависимости то же, что у {@link ru.locus.taxonomy.NodeContent}: спрашивает
 * тот, кого правило защищает, отвечает тот, кто знает ответ.
 */
public interface ProblemUsage {

    /** Где использована Задача; пусто — нигде. */
    Optional<String> of(ProblemId problem);
}
