package ru.locus.problem;

/**
 * Черновик Задачи изменён после того, как его прочитали (ADR-0056;
 * problem-intake, design.md, Р3).
 *
 * Правят черновик двое — Помощник инструментами и учитель на странице
 * вычитки. Запись, сохранение Задачей и удаление несут прочитанную версию;
 * если хранимая ушла вперёд, действие отклоняется целиком, а не
 * накатывается поверх: иначе чужая правка исчезла бы молча.
 */
public class ProblemDraftChangedException extends RuntimeException {

    public ProblemDraftChangedException() {
        super("Черновик Задачи изменён после того, как вы его прочитали, — перечитайте его");
    }
}
