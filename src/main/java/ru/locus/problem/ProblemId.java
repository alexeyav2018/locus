package ru.locus.problem;

/**
 * Идентификатор Задачи — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.taxonomy.TaxonomyNodeId}: разметка Задачи состоит
 * почти из одних идентификаторов — узлов дерева и записей двух словарей, —
 * и перепутанные местами числа не роняют запрос, а тихо размечают не ту
 * Задачу не тем Методом. Разные типы делают такую перестановку ошибкой
 * компиляции.
 *
 * Это же значение служит <b>номером</b> Задачи, под которым она видна
 * человеку: отдельного поля «номер» нет, потому что идентификатор и так
 * монотонно растёт, а второе поле с тем же смыслом разошлось бы с первым
 * молча (ADR-0029).
 *
 * Задача — общая библиотека, под Администратором; владельца у неё нет
 * и быть не должно (ADR-0027).
 */
public record ProblemId(long value) {

    public ProblemId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Задачи должен быть положительным: " + value);
        }
    }
}
