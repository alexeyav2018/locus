package ru.locus.problem;

/**
 * Текст Задачи изменился после того, как его прочитали (design.md изменения
 * {@code problem-text}, Р7).
 *
 * Правка несёт прочитанную версию текста; если хранимая ушла вперёд —
 * другой Администратор, а позже и помощник успели записать своё, — правка
 * отклоняется целиком, а не накатывается поверх: иначе чужой текст исчез
 * бы молча.
 */
public class ProblemTextChangedException extends RuntimeException {

    public ProblemTextChangedException() {
        super("Текст Задачи изменился после того, как открыта страница, — перечитайте её");
    }
}
