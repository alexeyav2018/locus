package ru.locus.assistant;

/**
 * Токен Реплики — личность Помощника на время одной Реплики (ADR-0057).
 *
 * <p>Локус выпускает его на Пользователя со сроком, Помощник предъявляет
 * его в каждом вызове сервера MCP заголовком {@code Authorization: Bearer},
 * по концу Реплики токен отзывается, а перезапуск убивает все: живут они
 * только в памяти ({@link TurnTokens}). Сам токен — одно значение; жив
 * он или нет, знает выпустившее его хранилище.
 *
 * <p>Значение — секрет, как пароль: утёкший токен до конца Реплики
 * действует от имени учителя. Поэтому {@link #toString()} значения
 * не раскрывает — токен не должен попасть в журнал ни отладочным
 * выводом, ни текстом исключения. Прочитать его можно только нарочно,
 * через {@link #value()}, и делает это тот, кто кладёт токен в заголовок.
 */
public record TurnToken(String value) {

    public TurnToken {
        if (value == null || value.isBlank()) {
            throw new IllegalArgumentException("Токен Реплики пуст");
        }
    }

    @Override
    public String toString() {
        return "TurnToken[скрыт]";
    }
}
