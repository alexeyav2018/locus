package ru.locus.work;

/**
 * Вердикт по Работе — «верно» либо «неверно» (glossary.md, «Перечисления»;
 * ADR-0014).
 *
 * Значения не придумываются по месту, а берутся из словаря: имя хранится
 * строкой в колонке {@code student_work.verdict} и переживёт любое
 * переименование, а придуманное здесь значение разошлось бы со словарём
 * молча.
 *
 * Третьего значения — «частично», «на доработку» — нет намеренно:
 * вердикт бинарный, частичность описывается примечанием (ADR-0014).
 * Состояние «не проверена» — это отсутствие вердикта у Работы
 * ({@code null} в записи и в колонке), а не константа здесь и не флаг
 * рядом (ADR-0038): состояние — это данные, а не отметка о них.
 */
public enum Verdict {

    CORRECT("верно"),

    INCORRECT("неверно");

    private final String title;

    Verdict(String title) {
        this.title = title;
    }

    /**
     * Название по-русски — для показа человеку. Перевод живёт здесь,
     * а не в шаблоне, по той же причине, что и у
     * {@link ru.locus.assignment.TheoryScope}: вердикт показывают и экран
     * приёма, и список Работ Ученика, и разъехались бы они молча
     * (ADR-0028: имена констант английские, интерфейс русский).
     */
    public String title() {
        return title;
    }
}
