package ru.locus.work;

/**
 * Справка по паре «Тема × Метод»: сколько проверенных Работ Ученика решены
 * верно и сколько проверено всего.
 *
 * Непроверенные Работы не считаются нигде: «не проверена» — отсутствие
 * вердикта (ADR-0038), и до вердикта Работа о владении не говорит ничего.
 * Это справка Учителю при простановке отметки, а не автоматика: суждение
 * выносит человек (ADR-0011, ADR-0014).
 */
public record Solved(int correct, int checked) {

    public Solved {
        if (correct < 0 || checked < correct) {
            throw new IllegalArgumentException("Верных решений не больше проверенных и не меньше нуля");
        }
    }
}
