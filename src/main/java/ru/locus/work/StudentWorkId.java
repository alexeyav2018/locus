package ru.locus.work;

/**
 * Идентификатор Работы — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.assignment.AssignmentId}: в вызовах
 * репозитория рядом с ним стоят идентификатор владельца
 * ({@link ru.locus.user.UserId}), идентификатор Задания и идентификатор
 * файла Работы. Перепутанные местами числа не роняют запрос — они тихо
 * правят не ту запись или отдают чужую; разные типы делают перестановку
 * ошибкой компиляции.
 *
 * Работа — личный контур: у записи есть владелец, и ни один запрос к ней
 * не идёт без него (ADR-0027).
 */
public record StudentWorkId(long value) {

    public StudentWorkId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Работы должен быть положительным: " + value);
        }
    }
}
