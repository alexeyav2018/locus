package ru.locus.work;

/**
 * Идентификатор файла Работы — отдельный тип, а не голое число.
 *
 * Файл Работы адресуется в запросах на удаление своим идентификатором,
 * а не ключом хранилища: ключ наружу не отдаётся вовсе — сканы работ суть
 * персональные данные детей, и единственный путь к содержимому — временная
 * подписанная ссылка (ADR-0021). Рядом с этим идентификатором в вызове
 * стоят идентификатор Работы и владельца; свой тип делает перестановку
 * ошибкой компиляции, как у {@link StudentWorkId}.
 */
public record StudentWorkFileId(long value) {

    public StudentWorkFileId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор файла Работы должен быть положительным: " + value);
        }
    }
}
