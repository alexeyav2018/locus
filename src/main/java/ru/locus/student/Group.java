package ru.locus.student;

import ru.locus.user.UserId;

/**
 * Группа — именованный список Учеников одного Учителя.
 *
 * Сама запись несёт только имя и владельца; состав живёт отдельно,
 * в таблице {@code group_student}, и читается через
 * {@link GroupRepository#members}. Группа — не суждение об Учениках,
 * а удобство выдачи: одно Задание на всех сразу (ADR-0035), поэтому
 * и удаляется она свободно, унося только свой список.
 *
 * Владелец обязателен по той же причине, что у {@link Student}: Группа
 * без владельца — Группа, которую увидят все (инвариант 11
 * domain-model.md, ADR-0027).
 *
 * Имя обязательно и не пустое после отсечения пробелов по краям.
 * В отличие от Ученика, оно уникально среди Групп одного владельца
 * без учёта регистра: Группа выбирается по имени при выдаче, и две «9Б»
 * неразличимы. Уникальность — дело репозитория и индекса
 * {@code uq_group_user_name}, а не записи: запись видит только себя.
 */
public record Group(GroupId id, UserId owner, String name) {

    public Group {
        if (owner == null) {
            throw new IllegalArgumentException("У Группы должен быть владелец");
        }
        if (name == null || name.isBlank()) {
            throw new IllegalArgumentException("Имя Группы не может быть пустым");
        }
    }
}
