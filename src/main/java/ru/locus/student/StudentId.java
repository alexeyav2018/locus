package ru.locus.student;

/**
 * Идентификатор Ученика — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.dictionary.SolutionMethodId}: в вызовах
 * репозитория рядом с ним стоит идентификатор владельца
 * ({@link ru.locus.user.UserId}), а скоро встанут и идентификаторы Группы,
 * Задания и Работы. Перепутанные местами числа не роняют запрос — они тихо
 * правят не ту запись или отдают чужую; разные типы делают перестановку
 * ошибкой компиляции.
 *
 * Ученик — личный контур: у записи есть владелец, и ни один запрос
 * к ней не идёт без него (ADR-0027).
 */
public record StudentId(long value) {

    public StudentId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Ученика должен быть положительным: " + value);
        }
    }
}
