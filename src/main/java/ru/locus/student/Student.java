package ru.locus.student;

import ru.locus.user.UserId;

/**
 * Ученик — карточка школьника у Учителя: имя, владелец и состояние выбытия.
 *
 * Ученик — объект учёта, а не пользователь (ADR-0003): учётной записи,
 * имени входа и пароля у него нет, и войти в систему ему нечем.
 * Взаимодействие с ним целиком идёт вне системы, и что ещё о нём записывать
 * — класс, контакты, примечание, — покажет практика; добавить поле дёшево,
 * угадывать его сейчас незачем.
 *
 * Владелец обязателен: Ученик принадлежит ровно одному Учителю
 * (инвариант 11 domain-model.md), и запись без владельца — это запись,
 * которую увидят все. Это первая запись личного контура, и владелец
 * в ней стоит явно, а не подразумевается контекстом (ADR-0027).
 *
 * Имя обязательно и не пустое после отсечения пробелов по краям;
 * уникальности у него нет: однофамильцы в одной группе обычны, а различить
 * их — дело Учителя.
 *
 * {@code withdrawn} — выбыл ли Ученик: занимался, перестал, историю терять
 * нельзя, но в повседневных списках и в выборе адресата при выдаче он
 * мешает (ADR-0040). Переключается Учителем в обе стороны свободно и ни на
 * что другое не влияет — ни на Задания, ни на Работы, ни на отметки
 * Владения, ни на членство в Группах.
 */
public record Student(StudentId id, UserId owner, String name, boolean withdrawn) {

    public Student {
        if (owner == null) {
            throw new IllegalArgumentException("У Ученика должен быть владелец");
        }
        if (name == null || name.isBlank()) {
            throw new IllegalArgumentException("Имя Ученика не может быть пустым");
        }
    }
}
