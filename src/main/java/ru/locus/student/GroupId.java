package ru.locus.student;

/**
 * Идентификатор Группы — отдельный тип, а не голое число.
 *
 * По образцу {@link StudentId}: в вызовах репозитория рядом с ним стоят
 * идентификатор владельца ({@link ru.locus.user.UserId}) и идентификаторы
 * Учеников состава. Перепутанные местами числа не роняют запрос — они тихо
 * правят не ту запись или отдают чужую; разные типы делают перестановку
 * ошибкой компиляции.
 *
 * Группа — личный контур: у записи есть владелец, и ни один запрос
 * к ней не идёт без него (ADR-0027).
 */
public record GroupId(long value) {

    public GroupId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Группы должен быть положительным: " + value);
        }
    }
}
