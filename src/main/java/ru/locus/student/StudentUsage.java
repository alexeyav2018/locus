package ru.locus.student;

import java.util.Optional;

/**
 * Вопрос, который область Учеников задаёт остальному личному контуру:
 * ссылается ли что-нибудь на этого Ученика?
 *
 * <p><b>Реализаций сегодня ни одной — и это не заглушка «на будущее»,
 * а честное состояние.</b> Ученик считается используемым, если на него
 * ссылается хотя бы одно Задание, хотя бы одна Работа или хотя бы одна
 * отметка Владения; ни того, ни другого, ни третьего в системе не существует,
 * поэтому список реализаций пуст, условие истинно тождественно, и удаление
 * Ученика сейчас проходит всегда (ADR-0035).
 *
 * <p><b>Появление каждой из трёх сущностей обязано ответить на этот
 * вопрос</b> своей реализацией:
 *
 * <ul>
 *   <li>Задание — Ученику что-то выдано; работа {@code assignments};</li>
 *   <li>Работа — от Ученика принято решение; работа
 *       {@code submission-review};</li>
 *   <li>отметка Владения — об Ученике вынесено суждение; работа
 *       {@code mastery-marks}.</li>
 * </ul>
 *
 * <p>Забытая реализация — тихая потеря данных: удаление Ученика с историей
 * уносит месяцы суждений о человеке, восстановить их неоткуда, а уведомлений
 * в системе нет (ADR-0035, ADR-0017). Одна реализация на область, а не три
 * метода в одном интерфейсе: области появятся в разное время, и каждая
 * приносит свою.
 *
 * <p>Направление зависимости — от отвечающих областей к {@code student},
 * как от {@code problem} к {@code dictionary}: спрашивает тот, кого правило
 * защищает, отвечает тот, кто знает ответ. Образец — {@link ru.locus.problem.ProblemUsage}.
 */
public interface StudentUsage {

    /** Что ссылается на Ученика; пусто — ничего. */
    Optional<String> of(StudentId student);
}
