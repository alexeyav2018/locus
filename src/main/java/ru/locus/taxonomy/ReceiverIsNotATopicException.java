package ru.locus.taxonomy;

/**
 * Указанный приёмник в состоянии дерева <b>после</b> операции не окажется
 * Темой, и содержимое, требующее Темы, принять не может (инвариант 1).
 *
 * Вид узла не хранится, а считается по потомкам, поэтому проверка смотрит
 * не на нынешнее дерево, а на то, каким оно станет: углубляемая Тема сейчас
 * Тема, но приёмником быть не может — потомок у неё вот-вот появится;
 * создаваемый потомок сейчас не существует, но приёмник законный
 * (design.md, «Проверка „приёмник — Тема“ считает состояние после операции»).
 */
public class ReceiverIsNotATopicException extends RuntimeException {

    public ReceiverIsNotATopicException(String message) {
        super(message);
    }
}
