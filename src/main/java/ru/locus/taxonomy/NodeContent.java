package ru.locus.taxonomy;

import java.util.Optional;

/**
 * Вопрос, который дерево задаёт остальным областям: что лежит на этом узле?
 *
 * Отвечают те области, которые что-то на узлы вешают: Задачи
 * ({@code problem-catalog}), Теоретические материалы
 * ({@code theory-materials}), отметки Владения ({@code mastery-marks}).
 * Реализации собираются списком, и {@link TaxonomyService} спрашивает всех,
 * не зная ни одной по имени.
 *
 * <p>Почему вопрос, а не прямой вызов: {@code problem} уже зависит
 * от {@code taxonomy} — идентификаторами узлов, — и дать
 * {@link TaxonomyService} репозиторий Задач означало бы круговую зависимость
 * областей. Каждое следующее содержимое добавляло бы ещё одну. При инверсии
 * появление теории или отметок — это новая реализация интерфейса в своей
 * области, без единой правки здесь (design.md, «Проверки в чужих областях»).
 *
 * <p>Ответ — не «да/нет», а описание для человека: отказ «на Теме есть Задачи
 * (3)» говорит, что делать дальше, а отказ «узел не пуст» — не говорит.
 */
public interface NodeContent {

    /**
     * Что эта область держит на узле; пусто — не держит ничего.
     *
     * Спрашивается перед удалением узла: удалить можно только пустой.
     */
    Optional<String> on(TaxonomyNodeId node);

    /**
     * То из содержимого узла, что <b>требует</b>, чтобы узел оставался Темой,
     * и потеряется, как только у узла появится потомок.
     *
     * Спрашивается перед созданием потомка. Отдельный вопрос, а не тот же
     * самый: Теоретический материал живёт на любом узле и углублению дерева
     * не мешает, а Задача и отметка Владения висят только на Теме (инвариант 1
     * и инвариант 3, domain-model.md) — и, став содержимым Раздела, они
     * перестают находиться в дереве и участвовать в статистике, причём молча.
     *
     * По умолчанию — пусто: содержимое, которому вид узла безразличен,
     * этот вопрос не переопределяет.
     */
    default Optional<String> requiringTopic(TaxonomyNodeId node) {
        return Optional.empty();
    }

    /**
     * Перевесить своё содержимое узла {@code from} на узел {@code to}.
     *
     * Спрашивается при углублении Темы: у Темы, несущей содержимое, появляется
     * потомок, и содержимое переезжает на <b>Тему-приёмник</b>, указанную
     * Администратором (ADR-0007). Дерево при этом по-прежнему не знает, что
     * именно переезжает и из какой области, — оно просит каждого ответчика
     * убрать за собой.
     *
     * <p>Вопрос здесь становится действием, и это сделано сознательно: всё,
     * что дерево спрашивает у чужих областей про узел, живёт в одном
     * интерфейсе. Второй, параллельный этому, забыли бы реализовать
     * наполовину — и содержимое осталось бы на узле, ставшем Разделом
     * (design.md, «Перевешивание метки — операция области Задач, а не
     * дерева»).
     *
     * <p>По умолчанию — ничего: содержимое, которому вид узла безразличен,
     * в переезде не участвует. Обязаны переопределить те, кто отвечает
     * на {@link #requiringTopic}: что требует Темы, то и обязано уехать.
     */
    default void moveTopicContent(TaxonomyNodeId from, TaxonomyNodeId to) {
        // Ничего: см. пояснение выше.
    }

    /**
     * Распределить своё содержимое снимаемой Темы {@code from} по приёмникам,
     * названным в {@code distribution}, — либо убрать его, если оно исчезает
     * вместе с Темой.
     *
     * Спрашивается при снятии Темы с распределением (ADR-0007): общего
     * приёмника у операции нет, Администратор назначает его каждой Задаче
     * отдельно. Дерево передаёт распределение, не читая его, — что в нём
     * названо и куда едет, знает только область содержимого, она же
     * и распознаёт свою часть распределения ({@link TopicDistribution}).
     *
     * <p>После того как все ответчики сделали своё, узел обязан быть пуст:
     * дерево переспрашивает {@link #on} и без этого узел не снимает.
     * Поэтому область, чьё содержимое требует Темы, отвечает здесь одним
     * из двух: перевешивает его на приёмники до последней единицы либо
     * снимает насовсем — то и другое своими средствами и под своими правами.
     * Половинный ответ — «часть уехала, часть осталась» — недопустим:
     * снятие отклоняется целиком, и разметка остаётся прежней.
     *
     * <p>По умолчанию — ничего: содержимое, которому вид узла безразличен,
     * распределению не подлежит, и узел с ним не снимается вовсе — дерево
     * отказывает до того, как спросить. Обязаны переопределить те, кто
     * отвечает на {@link #requiringTopic}.
     */
    default void distributeTopicContent(TaxonomyNodeId from, TopicDistribution distribution) {
        // Ничего: см. пояснение выше.
    }

    /**
     * Сколько своего исчезнет <b>невосполнимо</b> вместе с узлом.
     *
     * Спрашивается перед снятием Темы с распределением Задач: Администратору
     * показывается количественное предупреждение (ADR-0007). Считается только
     * то, что пропадает насовсем: Задачи не пропадают — они распределяются
     * по приёмникам, — а отметки Владения удаляемой Темы не сливаются ни
     * с кем и исчезают вместе с ней.
     *
     * <p>Наружу отдаётся <b>только число</b>. Ни ученика, ни учителя, ни
     * значения отметки Администратору не сообщается, и параметра владельца
     * у вопроса нет: показать лишнее ему нечем. Сам счёт при этом идёт
     * по <b>всем</b> учителям и по владельцу не фильтруется — единственное
     * во всей системе законное исключение из правила «Администратор не видит
     * личного контура учителей» (ADR-0005, ADR-0027). Исключение намеренное,
     * и потому названо здесь, а не оставлено на догадку читающего.
     *
     * <p>По умолчанию — ноль. Отвечать по существу обязана работа
     * {@code mastery-marks}: отметка, снятая вместе с Темой, невосполнима,
     * а пустое предупреждение выглядит убедительно и обнаружится только
     * по пропавшим суждениям. Долг сторожит {@code MasteryRestructureDebtTest}.
     */
    default int countVanishing(TaxonomyNodeId node) {
        return 0;
    }
}
