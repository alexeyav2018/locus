package ru.locus.taxonomy;

import java.util.Set;

/**
 * Распределение содержимого снимаемой Темы по Темам-приёмникам — то, что
 * Администратор назначил поштучно перед снятием (ADR-0007).
 *
 * <p>Дерево видит в распределении только <b>приёмников</b>: их оно проверяет
 * по состоянию дерева после снятия (design.md, «Проверка „приёмник — Тема“
 * считает состояние после операции»). Что именно и на какой из приёмников
 * едет, дерево не знает и знать не должно — это карта области содержимого,
 * и она же её читает, получив распределение обратно через
 * {@link NodeContent#distributeTopicContent}. Так граница областей остаётся
 * прежней: {@code problem} зависит от {@code taxonomy}, а не наоборот
 * (стережёт {@code TaxonomyKnowsNothingOfProblemsTest}).
 *
 * <p>Ключи карты потому и не выражены здесь: единственный способ назвать
 * Задачу в этом пакете — голое число, а голых идентификаторов в проекте нет
 * (standards.md, «Данные»).
 */
public interface TopicDistribution {

    /** Распределять нечего: у снимаемой Темы нет содержимого, ждущего приёмника. */
    TopicDistribution NOTHING = Set::of;

    /** Все узлы, названные приёмниками, — без повторов. */
    Set<TaxonomyNodeId> receivers();
}
