package ru.locus.taxonomy;

/**
 * Идентификатор узла рубрикатора — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.user.UserId}: в вызове с несколькими числовыми
 * аргументами — «перенести узел под узел» — перепутанные местами числа не
 * роняют запрос, а тихо перестраивают не то дерево. Разные типы делают такую
 * перестановку ошибкой компиляции.
 *
 * Узел рубрикатора — общее, под Администратором; владельца у него нет
 * и быть не должно (ADR-0027).
 */
public record TaxonomyNodeId(long value) {

    public TaxonomyNodeId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор узла рубрикатора должен быть положительным: " + value);
        }
    }
}
