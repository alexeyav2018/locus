package ru.locus.dictionary;

/**
 * Имя записи уникально в пределах своего словаря — и без учёта регистра.
 *
 * Уникальность здесь по всему словарю, а не среди братьев, как у узла
 * рубрикатора ({@link ru.locus.taxonomy.NameAlreadyTakenException}):
 * у плоского списка братья — это весь список. Регистр не учитывается по той
 * же причине: в дереве имя выбирается в коротком списке потомков одного
 * родителя и дубль виден глазом, а словарь на сотню записей просматривают
 * не целиком, и «Разложение на множители» рядом с «разложение на множители»
 * разошлись бы в две записи, а с ними и статистика владения (ADR-0010).
 *
 * От дублей <b>по смыслу</b> — «вынесение общего множителя» рядом
 * с «разложением на множители» — это не защищает и защищать не должно:
 * за них отвечает Администратор.
 */
public class NameAlreadyTakenException extends RuntimeException {

    private final String name;

    public NameAlreadyTakenException(String name) {
        super("Имя «" + name + "» уже занято в этом словаре");
        this.name = name;
    }

    public String name() {
        return name;
    }
}
