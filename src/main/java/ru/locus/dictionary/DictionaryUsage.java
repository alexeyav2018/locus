package ru.locus.dictionary;

import java.util.Optional;

/**
 * Вопрос, который словари задают остальным областям: употреблена ли эта
 * запись?
 *
 * Отвечают те области, которые на записи словарей ссылаются: разметка Задачи
 * ({@code problem-catalog}) и отметки Владения ({@code mastery-marks}, для
 * Метода). Реализации собираются списком, и сервисы словарей спрашивают всех,
 * не зная ни одной по имени.
 *
 * <p>Почему вопрос, а не прямой вызов: {@code problem} уже зависит
 * от {@code dictionary} — идентификаторами записей, — и дать
 * {@link SolutionMethodService} репозиторий Задач означало бы круговую
 * зависимость областей (design.md, «Проверки в чужих областях»).
 *
 * <p>Ответ — описание для человека, а не «да/нет»: отказ «Метод размечен
 * у Задач (4)» объясняет, почему удаление отклонено, и подсказывает, что
 * сначала снять.
 *
 * <p>Два вопроса вместо одного, потому что словаря два и они независимы:
 * одноимённые Метод и Характеристика — разные записи, и общий вопрос
 * потребовал бы различать их видом, а забытое условие на вид дало бы отказ
 * в удалении Характеристики из-за одноимённого Метода.
 */
public interface DictionaryUsage {

    /** Где употреблён Метод; пусто — нигде. */
    Optional<String> ofMethod(SolutionMethodId method);

    /** Где употреблена Характеристика; пусто — нигде. */
    Optional<String> ofCharacteristic(CharacteristicId characteristic);
}
