package ru.locus.dictionary;

/**
 * Удалять разрешено только неиспользуемую запись словаря.
 *
 * Используемая — та, на которую ссылается разметка хотя бы одной Задачи,
 * а впоследствии и отметки Владения. Отказ обязан быть внятным сообщением:
 * внешний ключ в схеме стоит вторым рубежом, но его срабатывание пришло бы
 * к Администратору исключением драйвера, а не объяснением (ADR-0010).
 */
public class EntryInUseException extends RuntimeException {

    public EntryInUseException(String message) {
        super(message);
    }
}
