package ru.locus.dictionary;

/**
 * Метод — приём решения задачи; вторая ось измерения владения, наравне
 * с Темой (ADR-0011).
 *
 * Запись состоит из идентификатора и имени, и больше ни из чего: ни родителя,
 * ни принадлежности Теме или Разделу у неё нет. Приём кочует между разделами
 * математики — «разложение на множители» встречается и в тригонометрических
 * уравнениях, и в показательных, — а расщеплённый по разделам Метод обратно
 * уже не собрать: история отметок к тому моменту разложена по разным ячейкам
 * (ADR-0010).
 *
 * Общего суперкласса или интерфейса с {@link Characteristic} здесь нет
 * намеренно: записи устроены одинаково, но роли у них разные, и связи
 * с Задачей у них появятся разные.
 */
public record SolutionMethod(SolutionMethodId id, String name) {

    public SolutionMethod {
        if (name == null || name.isBlank()) {
            throw new IllegalArgumentException("Имя Метода не может быть пустым");
        }
    }
}
