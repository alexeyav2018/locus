package ru.locus.assignment;

/**
 * Охват теории Задания — какие Теоретические материалы показывать к нему
 * (glossary.md, «Перечисления»; ADR-0018).
 *
 * Значения не придумываются по месту, а берутся из словаря: имя,
 * придуманное здесь, разошлось бы со словарём молча, а хранится оно строкой
 * в колонке {@code assignment.theory_scope} — то есть переживёт
 * и переименование.
 *
 * Охват задаётся при выдаче и после неё не меняется (ADR-0037), но сами
 * материалы к Заданию не прикрепляются: они вычисляются по Темам Задач
 * Задания при каждом показе, и материал, добавленный в библиотеку после
 * выдачи, тоже будет виден (ADR-0033).
 */
public enum TheoryScope {

    /** Материалы к Заданию не показываются вовсе. */
    NONE("без теории"),

    /** Только материалы, закреплённые на самих Темах Задач Задания. */
    TOPICS("только Темы задач"),

    /** Материалы Тем Задач вместе с материалами всех вышестоящих Разделов. */
    TOPICS_AND_SECTIONS("вместе с Разделами");

    private final String title;

    TheoryScope(String title) {
        this.title = title;
    }

    /**
     * Имя охвата по-русски — для показа человеку. Перевод живёт здесь,
     * а не в шаблоне, по той же причине, что и у {@link ru.locus.problem.ExamPart}:
     * охват показывают и форма выдачи, и страница Задания, и разъехались бы
     * они молча (ADR-0028: имена констант английские, интерфейс русский).
     */
    public String title() {
        return title;
    }
}
