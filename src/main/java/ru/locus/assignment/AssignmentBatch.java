package ru.locus.assignment;

import java.time.LocalDate;
import ru.locus.user.UserId;

/**
 * Раздача — общее происхождение Заданий, выданных Группе одним действием
 * (ADR-0016): после выдачи группе из двенадцати учитель видит не двенадцать
 * несвязанных строк, а один объект и может спросить «кто не сдал».
 *
 * <p>Раздача помнит <b>имя Группы</b>, а не саму Группу. Группа удаляется
 * в любой момент (ADR-0035) и переименовывается свободно; ссылка на неё
 * либо запретила бы удаление, либо обнулялась бы, теряя происхождение.
 * Имя на момент выдачи — исторический факт («выдано 9Б такого-то числа»),
 * а не производные данные, и переименование Группы его не переписывает.
 *
 * <p>Срока и охвата у Раздачи нет: они лежат на каждом Задании, потому что
 * срок переносится по одному, а Раздача — «лёгкая сущность, помнит
 * происхождение, не более» (ADR-0016). Раздача без Заданий не существует,
 * как Группа без Учеников: удаляется она вместе с ними, целиком или никак
 * (ADR-0037).
 *
 * <p>Владелец обязателен по той же причине, что у {@link Assignment}:
 * Раздача — личный контур (инвариант 11 domain-model.md, ADR-0027).
 * Имя обязательно и не пустое после отсечения пробелов по краям —
 * иначе Раздача от «ничего» неотличима от выданного лично.
 */
public record AssignmentBatch(AssignmentBatchId id, UserId owner, String groupName, LocalDate issuedOn) {

    public AssignmentBatch {
        if (owner == null) {
            throw new IllegalArgumentException("У Раздачи должен быть владелец");
        }
        if (groupName == null || groupName.isBlank()) {
            throw new IllegalArgumentException("Имя Группы в Раздаче не может быть пустым");
        }
        if (issuedOn == null) {
            throw new IllegalArgumentException("У Раздачи должна быть дата выдачи");
        }
    }
}
