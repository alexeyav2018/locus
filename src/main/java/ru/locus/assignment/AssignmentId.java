package ru.locus.assignment;

/**
 * Идентификатор Задания — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.student.StudentId}: в вызовах репозитория
 * рядом с ним стоят идентификатор владельца ({@link ru.locus.user.UserId}),
 * идентификатор Ученика и идентификатор Раздачи. Перепутанные местами числа
 * не роняют запрос — они тихо правят не ту запись или отдают чужую; разные
 * типы делают перестановку ошибкой компиляции.
 *
 * Задание — личный контур: у записи есть владелец, и ни один запрос
 * к ней не идёт без него (ADR-0027).
 */
public record AssignmentId(long value) {

    public AssignmentId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Задания должен быть положительным: " + value);
        }
    }
}
