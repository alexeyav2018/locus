package ru.locus.assignment;

/**
 * Идентификатор Раздачи — отдельный тип, а не голое число.
 *
 * По образцу {@link AssignmentId}: в вызовах репозитория рядом с ним стоит
 * идентификатор владельца ({@link ru.locus.user.UserId}), а в записи
 * Задания — идентификаторы Ученика и самого Задания. Перепутанные местами
 * числа не роняют запрос — они тихо правят не ту запись или отдают чужую;
 * разные типы делают перестановку ошибкой компиляции.
 *
 * Раздача — личный контур: у записи есть владелец, и ни один запрос
 * к ней не идёт без него (ADR-0027).
 */
public record AssignmentBatchId(long value) {

    public AssignmentBatchId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Раздачи должен быть положительным: " + value);
        }
    }
}
