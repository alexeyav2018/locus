package ru.locus.assignment;

import java.util.Collection;
import java.util.Set;

/**
 * Вопрос, который область Заданий задаёт остальному личному контуру:
 * есть ли по этим Заданиям хотя бы одна Работа?
 *
 * <p><b>Ответчик один — {@code WorksOfAssignment} области Работ</b>
 * (работа {@code submission-review}): Задание считается с Работой, как
 * только принята Работа хотя бы по одной его Задаче, и вердикт для этого
 * не нужен (ADR-0038). До появления Работ список реализаций был пуст,
 * ответ — тождественно пуст, и ни одно Задание не было сдано, а любое
 * удалялось; теперь оба следствия срабатывают по-настоящему —
 * сторожит {@code AssignmentWorkAnsweredTest}.
 *
 * <p>Ответ нужен в двух местах, и оба получают его вместе:
 *
 * <ul>
 *   <li><b>«не сдано»</b> — Задание, срок которого прошёл, а Работы нет
 *       (ADR-0016, инвариант 12: состояние вычисляется, не хранится);
 *       без ответа каждое просроченное Задание вечно «не сдано», сколько бы
 *       Работ по нему ни приняли;</li>
 *   <li><b>отказ в удалении</b> — Задание удаляется, пока по нему нет Работы
 *       (ADR-0037); без ответа Задание с Работами удаляется, и Работы
 *       повисают без основания, к которому привязаны.</li>
 * </ul>
 *
 * <p>Метод один на оба употребления намеренно: второй, «опиши, что держит»,
 * забыли бы реализовать вместе с первым, и половина правила осталась бы
 * пустой. Сообщение отказа — «по Заданию уже есть Работа» — собирает
 * область Заданий сама, ответчику хватает множества.
 *
 * <p>Владельца в вопросе нет — как у {@link ru.locus.student.StudentUsage}:
 * ответчик личный и владельца берёт у {@link ru.locus.user.CurrentUser} сам.
 * Направление зависимости — от {@code submission-review} к {@code assignment}:
 * спрашивает тот, кого правило защищает, отвечает тот, кто знает ответ.
 * Что вопрос и его ответчик названы здесь и в сервисе, сторожит
 * {@code AssignmentWorkDebtTest}.
 */
public interface AssignmentWork {

    /**
     * Задания из перечисленных, по которым есть хотя бы одна Работа.
     * Один вызов на весь список: Раздача удаляется или отклоняется целиком.
     */
    Set<AssignmentId> withWork(Collection<AssignmentId> assignments);
}
