package ru.locus.mastery;

/**
 * Шкала владения — четыре значения (glossary.md, «Перечисления»;
 * ADR-0012).
 *
 * Значения не придумываются по месту, а берутся из словаря: имя хранится
 * строкой в колонке {@code mastery.status} и переживёт любое
 * переименование, а придуманное здесь значение разошлось бы со словарём
 * молча.
 *
 * {@link #UNKNOWN} — единственное значение без суждения, и в базу оно
 * <b>не пишется</b> (ADR-0039): строка отметки существует только для трёх
 * значений с суждением, «неизвестно» — это отсутствие строки. Простановка
 * {@code UNKNOWN} у ячейки со строкой удаляет строку
 * ({@code MasteryRepository.put}); всё, что считает отметки, считает
 * строки — то есть только суждения.
 *
 * {@link #UNKNOWN} и {@link #NOT_MASTERED} — <b>разные</b> значения
 * и одно другим не подменяется нигде: первое — «сюда не ходили», второе —
 * суждение учителя (ADR-0012). Экран показывает оба своими словами,
 * счётчики второе считают, а первое — нет.
 */
public enum MasteryStatus {

    UNKNOWN("неизвестно"),

    NOT_MASTERED("не владеет"),

    UNCERTAIN("владеет неуверенно"),

    MASTERED("владеет");

    private final String title;

    MasteryStatus(String title) {
        this.title = title;
    }

    /**
     * Название по-русски — для показа человеку. Перевод живёт здесь,
     * а не в шаблоне, по той же причине, что и у {@link ru.locus.work.Verdict}:
     * значение показывают подпись ячейки и список выбора, и разъехались бы
     * они молча (ADR-0028: имена констант английские, интерфейс русский).
     */
    public String title() {
        return title;
    }

    /**
     * Есть ли за значением суждение учителя — то есть хранится ли оно
     * строкой в базе (ADR-0039). {@code false} только у {@link #UNKNOWN}.
     */
    public boolean isJudgement() {
        return this != UNKNOWN;
    }
}
