package ru.locus.file;

import java.net.URI;
import java.util.Optional;

/**
 * Хранилище файлов: положить, выдать временную ссылку, прочитать, удалить
 * (ADR-0021).
 *
 * Наружу содержимое уходит только по подписанной ссылке. Чтение по ключу —
 * для самой системы: страницы PDF на странице просмотра рисует сервер,
 * и рисовать их не из чего, кроме содержимого файла (ADR-0052). Права
 * на это чтение решает тот, кто вызывает, — как и на выдачу ссылки.
 *
 * Хранилище не знает, чьи файлы: {@code UserId} в его сигнатурах не появляется
 * ни здесь, ни в реализациях. Права решаются выше — в сервисе, который решает,
 * выдавать ли ссылку (ADR-0027). Не знает оно и о том, что именно лежит
 * по ключу: Задача это, Работа или Теория — забота вызывающего.
 */
public interface FileStorage {

    /**
     * Кладёт содержимое и возвращает ключ, по которому файл потом находится.
     * Ключ выдаёт хранилище — см. {@link FileKey}.
     *
     * @throws FileStorageUnavailableException если хранилище не отвечает
     */
    FileKey put(byte[] content, String contentType);

    /**
     * Временная подписанная ссылка на содержимое. Постоянного адреса у файла
     * нет ни в одной реализации: без действующей подписи содержимое
     * не отдаётся.
     *
     * Существование файла здесь не проверяется — ссылка выдаётся и на
     * отсутствующий ключ, а «файла нет» выясняется при обращении по ней.
     * Так устроено presign в объектном хранилище, и файловая реализация
     * повторяет это поведение, чтобы контракт был один.
     *
     * @throws FileStorageUnavailableException если хранилище не отвечает
     */
    URI temporaryLink(FileKey key);

    /**
     * Содержимое файла по ключу. Пустой результат — «файла нет», и он
     * не различает «никогда не существовал» и «удалён», как ссылка.
     *
     * @throws FileStorageUnavailableException если хранилище не отвечает:
     *         недоступность не должна выглядеть как отсутствие файла
     */
    Optional<byte[]> read(FileKey key);

    /**
     * Удаляет файл. Удаление отсутствующего файла — не ошибка: повторный вызов
     * после сбоя не должен требовать разбирательства, был ли файл удалён
     * в прошлый раз.
     *
     * @throws FileStorageUnavailableException если хранилище не отвечает
     */
    void delete(FileKey key);
}
