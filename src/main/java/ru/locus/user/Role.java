package ru.locus.user;

/**
 * Роль — набор прав, а не режим работы. Активная роль не выбирается: вошедший
 * получает объединённый функционал всех своих ролей (ADR-0005).
 *
 * Значения названы по словарю (glossary.md, раздел «Перечисления») и в таком же
 * виде лежат в базе. Префикс {@code ROLE_}, которого требует Spring Security, —
 * деталь фреймворка: он добавляется при построении {@code UserDetails}
 * и в базу не попадает.
 */
public enum Role {

    /** Владеет общим: рубрикатор, словари, задачи, теория, учётные записи. */
    ADMINISTRATOR,

    /** Владеет личным: ученики, группы, задания, работы, отметки владения. */
    TEACHER
}
