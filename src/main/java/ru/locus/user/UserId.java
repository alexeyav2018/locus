package ru.locus.user;

/**
 * Идентификатор Пользователя — отдельный тип, а не голое число.
 *
 * Так требует ADR-0027: владелец личных данных стоит в сигнатурах репозиториев
 * явным обязательным параметром, и в вызове с несколькими числовыми аргументами
 * его не должно быть возможно перепутать с чужим идентификатором. Перепутанный
 * идентификатор не роняет запрос — он тихо отдаёт чужие данные.
 */
public record UserId(long value) {

    public UserId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Пользователя должен быть положительным: " + value);
        }
    }
}
