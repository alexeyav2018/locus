package ru.locus.warmup;

/**
 * Итог Разминки — «справился» либо «не справился» на паре «Ученик × Задача»
 * (glossary.md, «Перечисления»; ADR-0061).
 *
 * Имя хранится строкой в колонке {@code warmup_outcome.outcome}, как
 * у {@link ru.locus.work.Verdict}: значения берутся из словаря, а не
 * придумываются по месту.
 *
 * Пустоты среди значений нет намеренно: пустая клетка — Ученик эту Задачу
 * не писал или до неё не дошли — это отсутствие строки, а не константа
 * здесь (ADR-0061, как «неизвестно» у отметки, ADR-0039). «Не справился» —
 * суждение, а не «не решал».
 */
public enum WarmupOutcome {

    SUCCEEDED("справился"),

    FAILED("не справился");

    private final String title;

    WarmupOutcome(String title) {
        this.title = title;
    }

    /**
     * Название по-русски — для показа человеку. Перевод живёт здесь,
     * а не в шаблоне, как у {@link ru.locus.work.Verdict}: итог показывают
     * и страница Разминки, и её список, и разъехались бы они молча
     * (ADR-0028: имена констант английские, интерфейс русский).
     */
    public String title() {
        return title;
    }
}
