package ru.locus.warmup;

/**
 * Идентификатор Разминки — отдельный тип, а не голое число.
 *
 * По образцу {@link ru.locus.assignment.AssignmentId}: в вызовах репозитория
 * рядом с ним стоят идентификаторы владельца, Ученика и Задачи, и
 * перепутанные местами числа не роняют запрос, а тихо правят не ту запись;
 * разные типы делают перестановку ошибкой компиляции.
 *
 * Разминка — личный контур: у записи есть владелец, и ни один запрос
 * к ней не идёт без него (ADR-0027).
 */
public record WarmupId(long value) {

    public WarmupId {
        if (value <= 0) {
            throw new IllegalArgumentException("Идентификатор Разминки должен быть положительным: " + value);
        }
    }
}
